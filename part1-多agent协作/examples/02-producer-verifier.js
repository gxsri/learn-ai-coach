/**
 * 例 2 · 生产者 + 验证者（Producer / Verifier）
 * ---------------------------------------------------------------
 * 练什么：多 agent 相对单 agent「唯一真正变强」的地方 —— 独立视角的挑错。
 *
 * 为什么要两个 agent：
 *   同一个 agent 写完后你让它"再检查一遍"，它倾向于回答"检查过了，没问题"，
 *   因为它要给自己刚写的东西背书。换一个没有这段上下文的 agent，
 *   它才真的会去挑错。
 *
 * 关键：审校 agent 必须拿到「挑错的许可」+「核实的手段」。
 *
 * meta（配套填写）：
 * {
 *   "name": "producer-verifier",
 *   "description": "一个 agent 写技术说明，另一个专门找错并核实",
 *   "phases": [
 *     { "title": "产出", "detail": "写手 agent 产出初稿" },
 *     { "title": "审校", "detail": "审校 agent 联网核实并挑错" }
 *   ]
 * }
 */

const 主题 = '在 Windows + Python 3.12 + RTX 4060 8GB 上安装并跑通 Ultralytics YOLO 的姿态估计'
const 文件 = 'D:/program/learn-ai-coach/part1-多agent协作/examples/_demo-初稿.md'

// ── 阶段一：产出 ──────────────────────────────────────────────────────────
phase('产出')

const 初稿 = await agent(
  `你是技术写手。请写一份中文操作说明，主题：${主题}。

要求：
- 用 web_search 至少检索 2 次，确认库名、安装命令、模型权重文件名真实存在；不确定的必须标注「待核实」。
- 结构：安装步骤（带完整命令）/ 最小可运行代码 / 常见报错 / 版本与许可证注意事项。
- 600-1000 字，禁止客套话。
- 用 write 工具把成稿写入：${文件}
- 写完只返回 3 行摘要。`,
  { label: '写手 · 初稿', phase: '产出' },
)

// ── 阶段二：审校 ──────────────────────────────────────────────────────────
phase('审校')

// 注意这个 prompt 的写法：明确授权挑错、要求逐条核实、要求分级。
// 「找到越多越好」这句话很重要 —— 不说，它就容易只挑一两个意思一下。
const 意见 = await agent(
  `你是技术审校。你的唯一任务是**找出错误**，找到越多越好。

请用 read 工具读取：${文件}

然后逐条检查：
1. 事实性错误：不存在的库名 / 模型权重文件名 / 命令行参数 / 版本号。
   对每一个可疑点，用 web_search 核实，不要凭印象判断。
2. 命令能不能真的跑通：路径是否完整、有没有留下省略号、参数拼写对不对。
3. 遗漏：有没有该提醒但没提的坑（比如依赖冲突、许可证、显存不足）。

对每条问题给出：严重程度（高/中/低）、原文出处、错在哪、正确说法是什么。
如果某条你不确定，明确写「不确定」，不要猜。

最后只返回最严重的 3 条，格式：严重程度 | 问题 | 正确说法。`,
  { label: '审校 · 挑错', phase: '审校' },
)

return {
  初稿长度: 初稿 ? 初稿.length : 0,
  初稿文件: 文件,
  审校意见: 意见,
}
