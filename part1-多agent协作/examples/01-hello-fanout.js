/**
 * 例 1 · 最小扇出（Hello Fan-out）
 * ---------------------------------------------------------------
 * 练什么：parallel 的最基本用法 —— 同时开几个 agent，逐个收结果。
 *
 * meta（配套填写）：
 * {
 *   "name": "hello-fanout",
 *   "description": "三个 agent 并行解释同一个概念的三个侧面",
 *   "phases": [{ "title": "扇出" }]
 * }
 */

// 三个互不依赖的子任务。注意每个 prompt 都是自包含的：
// 子 agent 看不到你的对话，所以背景必须写全。
const 任务 = [
  {
    标签: '概念',
    提示: '用一段话（150 字以内）解释「人体姿态估计」是什么，面向一个有 AI 概念但没做过视觉项目的人。'
      + '不要用"简单来说"，不要客套。直接给结论。',
  },
  {
    标签: '输入输出',
    提示: '用一段话（150 字以内）说明姿态估计模型的「输入」和「输出」分别是什么。'
      + '输出部分要提到关键点坐标和置信度。直接给结论，不要铺垫。',
  },
  {
    标签: '用途',
    提示: '用一段话（150 字以内）列举姿态估计在体育分析里的三个具体用途，每个用途一句话。'
      + '直接给列表，不要开场白。',
  },
]

phase('扇出')

// parallel 收到一组「零参数函数」，全部跑完才返回。
// 某个函数抛错 → 那一项变成 null，不影响其它项。
const 结果 = await parallel(
  任务.map((t) => () => agent(t.提示, { label: t.标签, phase: '扇出' })),
)

// 把结果拼成一份可读的分节文本
const 成稿 = 任务
  .map((t, i) => `## ${t.标签}\n\n${结果[i] ?? '（这一路失败了）'}`)
  .join('\n\n')

return {
  成功数: 结果.filter(Boolean).length,
  总数: 任务.length,
  成稿,
}
