/**
 * 例 4 · 调研流水线（Pipeline）
 * ---------------------------------------------------------------
 * 练什么：
 *   - pipeline 的用法：每个素材独立走完全部 stage，stage 之间没有栅栏
 *   - 让 agent 把大产物写进文件，只返回短摘要（保护你自己的上下文）
 *   - 显式报告失败项（filter(Boolean) 会静默吞掉失败，一定要单独报出来）
 *
 * 这个例子就是本教程 research/ 目录那 6 份笔记的产出方式。
 *
 * meta（配套填写）：
 * {
 *   "name": "research-pipeline",
 *   "description": "多专题并行：调研 → 核实 → 整理成稿，并报告失败项",
 *   "phases": [
 *     { "title": "调研", "detail": "每个专题一个 agent 联网检索并落盘" },
 *     { "title": "核实", "detail": "换一个 agent 逐条核实上一阶段的断言" }
 *   ]
 * }
 */

const 输出目录 = 'D:/program/learn-ai-coach/research'

// 每个元素都会被送进下面所有 stage。
// 这里用对象，好让 stage 知道「写到哪个文件、要写什么」。
const 专题 = [
  {
    文件: 'T1-球轨迹追踪.md',
    标题: '羽毛球球轨迹追踪',
    要求: 'TrackNet 系列（V2/V3）的原理、与普通目标检测的区别、为什么高速小球不能用检测框、输入输出格式、开源实现与权重名',
  },
  {
    文件: 'T2-场地标定.md',
    标题: '场地标定与像素到米的换算',
    要求: '羽毛球场标准尺寸、球场线检测思路、四点对应求单应矩阵 cv2.findHomography、重投影误差怎么检查、perspectiveTransform 换算',
  },
  {
    文件: 'T3-击球事件检测.md',
    标题: '击球时刻的自动检测',
    要求: '用骨架的手腕速度峰值、用球轨迹转折、用击球声 onset，三种信号的原理与取舍，以及如何对齐到同一时间轴',
  },
]

phase('调研')

const 结果 = await pipeline(
  专题,

  // ── stage 1：调研 ──────────────────────────────────────────────────────
  (_prev, 项) =>
    agent(
      `你是技术调研员。请调研专题：${项.标题}

必须覆盖：${项.要求}

要求：
- 用 web_search 至少检索 3 次，核对库名、权重文件名、命令是否真实存在。禁止编造。
- 全中文 Markdown，结构：一句话结论 / 核心概念 / 可执行的最短路径 / 常见坑 / 参考链接。
- 600-1200 字，附来源链接，不确定的标注「待核实」。
- 用 write 工具把笔记写入：${输出目录}/${项.文件}
- 写完只返回 5 行以内的摘要。`,
      { label: `调研 · ${项.标题}`, phase: '调研' },
    ),

  // ── stage 2：核实 ──────────────────────────────────────────────────────
  // prev 是 stage 1 的返回值（那段摘要），项 仍是当前对象。
  // 核实 agent 直接去读落盘的完整文件，而不是靠摘要判断。
  (prev, 项) =>
    agent(
      `你是事实核查员。请用 read 工具读取文件：${输出目录}/${项.文件}

逐条检查：
1. 有没有不存在的库名 / 权重文件名 / 命令行参数 / 版本号？对可疑点用 web_search 核实。
2. 有没有前后自相矛盾的说法？
3. 有没有该讲但没讲的关键环节？

把核查结论写入：${输出目录}/REVIEW-${项.文件}
只返回最严重的 3 条，格式：问题 | 错在哪 | 正确说法。
如果确实没发现问题，就明确说「未发现问题」，不要硬凑。`,
      { label: `核实 · ${项.标题}`, phase: '核实' },
    ),
)

// ── 关键：把失败项显式报出来 ─────────────────────────────────────────────
// 如果只写 结果.filter(Boolean).length，你会看到「成功 2 / 共 3」
// 却不知道是哪一个失败。下面这样写，主 agent 才能自己去补那一个。
const 失败的 = 专题.filter((_, i) => !结果[i]).map((x) => x.标题)

return {
  成功数: 结果.filter(Boolean).length,
  总数: 专题.length,
  失败的专题: 失败的.length > 0 ? 失败的 : '无',
  产出文件: 专题.map((x) => `${输出目录}/${x.文件}`),
  各专题核查摘要: 结果.map((r, i) => ({ 标题: 专题[i].标题, 摘要: r ?? '（该专题失败）' })),
}
